package ru.repitbot.api.auth;

/** Текст согласия на обработку ПД на странице приглашения (обычный текст, абзацы через пустую строку). */
public final class ConsentText {

    private ConsentText() {
    }

    /**
     * @param tutorName имя репетитора или null, если он ещё не настроен
     * @param childName имя ребёнка для приглашения родителя, null для ученика
     */
    public static String render(String tutorName, String childName) {
        boolean parent = childName != null;
        String operator = tutorName == null ? "репетитору" : tutorName;

        String whoData = parent
                ? "• ваше имя и имя вашего ребёнка (" + childName + ");\n"
                : "• имя и фамилию ученика (и родителя, если он подключён);\n";
        String agreement = parent
                ? "согласие на обработку ваших персональных данных и данных вашего ребёнка"
                : "согласие на обработку указанных персональных данных";

        return "Здесь можно смотреть расписание и получать напоминания о занятиях, сдавать домашние задания "
                + "и получать оценки, видеть, сколько занятий абонемента проведено.\n\n"
                + "Какие данные хранятся:\n"
                + whoData
                + "• логин (пароль хранится только в зашифрованном виде);\n"
                + "• расписание, посещаемость, домашние задания с файлами, оценки и отметки об оплате.\n\n"
                + "Зачем: только для проведения занятий, напоминаний и отчётов родителям. "
                + "Данные не передаются третьим лицам и не используются для рекламы.\n\n"
                + "Уведомления, если вы их включите, доставляет служба вашего браузера (Google, Apple или Mozilla) "
                + "в зашифрованном виде — прочитать их она не может.\n\n"
                + "Сайт хранит одну cookie — чтобы вы оставались в аккаунте. Аналитики и рекламы нет.\n\n"
                + "Где: на защищённом сервере в России.\n\n"
                + "Как долго: пока идут занятия и ещё 1 год после последнего занятия, потом данные удаляются.\n\n"
                + "Как отозвать: в любой момент в настройках — «Удалить мои данные». "
                + "Данные будут удалены в течение 30 дней.\n\n"
                + "Отмечая согласие, вы даёте " + operator + " " + agreement
                + " по Федеральному закону № 152-ФЗ «О персональных данных»."
                + (parent ? "" : "\nЕсли ученику меньше 14 лет, регистрироваться и давать согласие должен родитель.");
    }
}
